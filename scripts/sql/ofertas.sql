-- Ofertas do checkout: cupons de desconto, order bump, upsell, combos e brindes,
-- mais as configuracoes gerais (ex.: % de desconto no Pix).
-- Rode inteiro, uma vez, no SQL Editor do Supabase. E seguro rodar de novo.
--
-- IMPORTANTE: rode este script ANTES (ou logo depois) de publicar o checkout novo.
-- Se as tabelas ainda nao existirem, o site continua vendendo normalmente, so que
-- sem cupons/ofertas e com o desconto do Pix no valor padrao (4%).
--
-- Pre-requisito: scripts/sql/seguranca.sql ja aplicado (cria public.eh_admin()).

-- 1) Configuracoes gerais (chave/valor)
create table if not exists public."Configuracoes" (
  chave text primary key,
  valor text
);
insert into public."Configuracoes" (chave, valor) values ('pix_desconto_pct', '4')
  on conflict (chave) do nothing;

-- 2) Cupons de desconto
create table if not exists public."Cupons" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  codigo text not null unique,            -- sempre MAIUSCULO, ex.: BEMVINDO10
  descricao text,
  tipo text not null default 'percentual', -- 'percentual' | 'valor'
  valor numeric not null,                  -- 10 = 10% (percentual) ou R$ 10,00 (valor)
  minimo numeric not null default 0,       -- subtotal minimo do pedido
  limite_usos integer,                     -- null = ilimitado
  usos integer not null default 0,
  validade date,                           -- null = sem validade (vale ate o fim do dia)
  ativo boolean not null default true
);

-- 3) Ofertas: order bump, upsell, combo e brinde
create table if not exists public."Ofertas" (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  tipo text not null,                      -- 'order_bump' | 'upsell' | 'combo' | 'brinde'
  nome text not null,                      -- nome interno (so aparece no admin e no resumo)
  ativo boolean not null default true,
  ordem integer not null default 0,
  titulo text,                             -- titulo do card no checkout
  descricao text,                          -- texto de apoio do card
  produto_id text,                         -- order_bump/upsell: produto ofertado | brinde: produto que vira brinde
  gatilho_id text,                         -- order_bump: so aparece se este produto estiver no carrinho (vazio = sempre)
                                           -- upsell: produto do carrinho que sera trocado pelo produto ofertado
  desconto_pct numeric not null default 0, -- order_bump/upsell: % de desconto sobre o preco do produto
  itens_combo jsonb,                       -- combo: lista de ids de produto, ex.: ["12","15"]
  preco_fechado numeric,                   -- combo: preco do kit completo
  qtd_minima integer                       -- brinde: quantidade de produtos no carrinho para ganhar
);
create index if not exists ofertas_tipo_idx on public."Ofertas" (tipo, ativo);

-- 4) Uso de cupom (incremento atomico, chamado pelas funcoes do Netlify com a chave de servico)
create or replace function public.usar_cupom(p_codigo text)
returns void
language sql
as $$
  update public."Cupons" set usos = usos + 1 where codigo = upper(p_codigo);
$$;
revoke all on function public.usar_cupom(text) from public, anon, authenticated;

-- 5) Seguranca (RLS)
alter table public."Configuracoes" enable row level security;
alter table public."Cupons"        enable row level security;
alter table public."Ofertas"       enable row level security;

drop policy if exists "Configuracoes leitura publica" on public."Configuracoes";
create policy "Configuracoes leitura publica" on public."Configuracoes"
  for select to anon, authenticated using (true);

drop policy if exists "Ofertas leitura publica" on public."Ofertas";
create policy "Ofertas leitura publica" on public."Ofertas"
  for select to anon, authenticated using (ativo = true);

-- Cupons NAO sao publicos (ninguem pode listar os codigos): so o admin le/escreve
-- e as funcoes do Netlify (chave de servico) validam o codigo digitado.
revoke all on public."Cupons" from anon;

do $$
begin
  if to_regprocedure('public.eh_admin()') is null then
    raise exception 'Rode antes o scripts/sql/seguranca.sql (cria public.eh_admin()).';
  end if;
end $$;

drop policy if exists "Configuracoes admin" on public."Configuracoes";
create policy "Configuracoes admin" on public."Configuracoes"
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "Ofertas admin" on public."Ofertas";
create policy "Ofertas admin" on public."Ofertas"
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

drop policy if exists "Cupons admin" on public."Cupons";
create policy "Cupons admin" on public."Cupons"
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

revoke insert, update, delete, truncate on public."Configuracoes", public."Ofertas" from anon;
